    val all: List<Quote> get() = english + polish

    fun forLanguage(language: Language): List<Quote> = when (language) {
        Language.ENGLISH -> english
        Language.POLISH -> polish
    }

    fun forDifficulty(difficulty: Difficulty, language: Language): List<Quote> {
        val pool = forLanguage(language)
        return pool.filter { it.text.length in difficulty.lengthRange }.ifEmpty { pool }
    }

    /** A random quote for [difficulty] in [language], avoiding [exclude] when possible. */
    fun random(
        difficulty: Difficulty,
        language: Language,
        exclude: String? = null,
        random: Random = Random.Default,
    ): Quote {
        val pool = forDifficulty(difficulty, language)
        return pool.filter { !it.text.equals(exclude, ignoreCase = true) }.ifEmpty { pool }.random(random)
    }
